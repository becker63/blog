import { asc, desc, eq } from "drizzle-orm";
import type { NeonHttpDatabase } from "drizzle-orm/neon-http";

import * as schema from "../schema";

type MetricSnapshotRow = typeof schema.metricSnapshots.$inferSelect;

function sumMetricColumn(
  rows: MetricSnapshotRow[],
  col: keyof Pick<MetricSnapshotRow, "impressions" | "views" | "reactions" | "comments" | "reposts">,
): number {
  return rows.reduce((acc, row) => {
    const v = row[col];
    return acc + (typeof v === "number" && Number.isFinite(v) ? v : 0);
  }, 0);
}

/** Assemble Markdown for `launch_reports` rows (cron + admin preview). */
export async function compileLaunchReportMarkdown(
  db: NeonHttpDatabase<typeof schema>,
  launchId: string,
  postingJobId: string | null,
): Promise<string> {
  const [launch] = await db.select().from(schema.launches).where(eq(schema.launches.id, launchId)).limit(1);
  if (!launch) throw new Error("launch_not_found");

  const pubs = await db
    .select()
    .from(schema.publications)
    .where(eq(schema.publications.launchId, launchId))
    .orderBy(desc(schema.publications.updatedAt))
    .limit(30);

  const metrics = await db
    .select()
    .from(schema.metricSnapshots)
    .where(eq(schema.metricSnapshots.launchId, launchId))
    .orderBy(desc(schema.metricSnapshots.capturedAt))
    .limit(30);

  let jobEvents: Array<typeof schema.launchPostJobEvents.$inferSelect> = [];
  if (postingJobId) {
    jobEvents = await db
      .select()
      .from(schema.launchPostJobEvents)
      .where(eq(schema.launchPostJobEvents.jobId, postingJobId))
      .orderBy(asc(schema.launchPostJobEvents.createdAt))
      .limit(80);
  }

  const impressions = sumMetricColumn(metrics, "impressions");
  const views = sumMetricColumn(metrics, "views");
  const reactions = sumMetricColumn(metrics, "reactions");
  const comments = sumMetricColumn(metrics, "comments");
  const reposts = sumMetricColumn(metrics, "reposts");

  const lines: string[] = [
    `# Launch report: ${launch.title}`,
    "",
    `**Canonical path:** ${launch.canonicalPath}`,
    `**Post slug:** ${launch.postSlug}`,
    `**Primary claim:** ${launch.primaryClaim}`,
    `**Audience gate:** ${launch.audienceGate}`,
    `**Launch DB status:** ${launch.status}`,
    "",
    "## Publications",
    ...(pubs.length
      ? pubs.map((p) => `- ${p.provider}: ${p.status} · ${p.url ?? p.platformPostId ?? "(no URL)"}`)
      : ["- (none)"]),
    "",
    "## Metric snapshots aggregate (recent window)",
    `- impressions Σ: ${impressions || "n/a"}`,
    `- views Σ: ${views || "n/a"}`,
    `- reactions Σ: ${reactions || "n/a"}`,
    `- comments Σ: ${comments || "n/a"}`,
    `- reposts Σ: ${reposts || "n/a"}`,
    "",
    "## Recent metric rows",
    ...(metrics.slice(0, 15).length
      ? metrics
          .slice(0, 15)
          .map(
            (s) =>
              `- ${s.capturedAt.toISOString()} (${s.source}) ${s.provider ?? ""} impressions=${s.impressions ?? "—"} views=${s.views ?? "—"}`,
          )
      : ["- (none)"]),
  ];

  if (postingJobId) {
    lines.push(
      "",
      "## Related posting job timeline",
      ...jobEvents.map((e) => `- ${e.createdAt.toISOString()} · ${e.eventType}: ${e.message ?? ""}`),
    );
  }

  lines.push(
    "",
    "_Generated by `render_report` cron (PublicProof)._",
    `_Job ref: ${postingJobId ?? "n/a"}_`,
  );

  return lines.join("\n");
}
